import { useState, useEffect, useCallback } from "react";
import { useTheme } from "../../ThemeContext";
import { supabase } from "../../../lib/supabaseClient";
import { AdminRoleModal } from "./AdminRoleModal";
import { AdminBulkResultModal } from "./AdminBulkResultModal";
import { AdminMfaResetModal } from "./AdminMfaResetModal";

interface AdminUserManagementProps {
  refreshKey: number;
  adminId: string;
}

const ROLE_CFG: Record<string, { label: string }> = {
  admin:       { label: "관리자" },
  participant: { label: "참여사 담당자" },
  user:        { label: "일반 회원" },
};
const ROLE_LABELS: Record<string, string> = { admin: "관리자", participant: "참여사 담당자", user: "일반 회원" };

const STATUS_CFG: Record<string, { label: string; fg: string; bg: string; border: string }> = {
  pending:  { label: "승인 대기", fg: "var(--color-brand-yellow)", bg: "rgba(245,158,11,0.12)", border: "rgba(245,158,11,0.32)" },
  approved: { label: "승인됨",   fg: "#16B886",                   bg: "rgba(34,214,162,0.12)", border: "rgba(34,214,162,0.32)" },
  rejected: { label: "반려됨",   fg: "var(--color-brand-red)",     bg: "rgba(234,67,53,0.10)",  border: "rgba(234,67,53,0.30)" },
};

type RegisterResult = { email: string; name: string; success: boolean; tempPassword?: string; wasAutoGenerated?: boolean; error?: string };

type AdminUserRow = {
  id: string;
  email: string | null;
  name: string | null;
  company: string | null;
  role: string | null;
  status: string | null;
};

async function extractFunctionErrorMessage(error: unknown, fallback: string) {
  const context = typeof error === "object" && error !== null && "context" in error
    ? (error as { context?: unknown }).context
    : null;

  if (context instanceof Response) {
    try {
      const payload = await context.clone().json() as { error?: string; message?: string };
      if (typeof payload.error === "string" && payload.error.trim()) return payload.error;
      if (typeof payload.message === "string" && payload.message.trim()) return payload.message;
    } catch {
      try {
        const text = await context.clone().text();
        if (text.trim()) return text;
      } catch {
        // Ignore body parsing failures and fall through to generic handling.
      }
    }
  }

  if (error instanceof Error && error.message && !error.message.includes("non-2xx")) {
    return error.message;
  }

  return fallback;
}

export function AdminUserManagement({ refreshKey, adminId }: AdminUserManagementProps) {
  const { isDark } = useTheme();

  const [users, setUsers]               = useState<AdminUserRow[]>([]);
  const [loading, setLoading]           = useState(true);
  const [search, setSearch]             = useState("");
  const [currentPage, setCurrentPage]   = useState(1);
  const [csvLoading, setCsvLoading]     = useState(false);
  const [bulkResult, setBulkResult]     = useState<{ results: RegisterResult[] } | null>(null);

  const [pendingRoleChange, setPendingRoleChange] = useState<{ userId: string; newRole: string; targetName: string; currentRole: string } | null>(null);
  const [pendingMfaReset, setPendingMfaReset] = useState<{ userId: string; targetName: string } | null>(null);
  const [roleConfirmPassword, setRoleConfirmPassword] = useState("");
  const [roleConfirmLoading, setRoleConfirmLoading]   = useState(false);
  const [showRolePassword, setShowRolePassword]       = useState(false);

  const usersPerPage = 10;

  const card     = isDark ? "rgba(255,255,255,0.04)" : "#ffffff";
  const border   = isDark ? "rgba(255,255,255,0.08)" : "rgba(0,0,0,0.08)";
  const textMain = isDark ? "rgba(255,255,255,0.92)" : "rgba(10,16,32,0.88)";
  const textMuted= isDark ? "rgba(255,255,255,0.45)" : "rgba(10,16,32,0.45)";
  const inputBg  = isDark ? "rgba(255,255,255,0.04)" : "#fff";
  const skBg     = isDark ? "rgba(255,255,255,0.07)" : "rgba(0,0,0,0.06)";
  const panelBg = isDark ? "rgba(255,255,255,0.035)" : "rgba(15,23,42,0.035)";
  const selectedBg = isDark ? "rgba(255,255,255,0.10)" : "rgba(15,23,42,0.07)";
  const labelBg = isDark ? "rgba(255,255,255,0.045)" : "rgba(15,23,42,0.035)";
  const labelBorder = isDark ? "rgba(255,255,255,0.10)" : "rgba(15,23,42,0.09)";
  const deleteBg = isDark ? "rgba(234,67,53,0.08)" : "rgba(234,67,53,0.06)";
  const deleteBorder = isDark ? "rgba(234,67,53,0.28)" : "rgba(234,67,53,0.22)";

  const Sk = ({ h = 78 }: { h?: number }) => (
    <div style={{ height: h, borderRadius: 16, background: skBg, animation: "pulse 1.5s ease-in-out infinite" }} />
  );

  const fetchUsers = useCallback(async () => {
    setLoading(true);
    const { data, error } = await supabase.functions.invoke('decrypt-profiles');
    if (error) console.error("회원 데이터 불러오기 오류:", error.message);
    if (data) setUsers(data as AdminUserRow[]);
    setLoading(false);
  }, []);

  useEffect(() => { fetchUsers(); }, [refreshKey]);

  // ── 역할 변경 ──────────────────────────────────────────────
  const handleSetRole = async (id: string, newRole: string) => {
    if (id === adminId) { alert("본인 계정의 권한은 변경할 수 없습니다."); return; }
    const target = users.find(u => u.id === id);
    const currentRole = target?.role ?? "user";
    if (currentRole === newRole) return;
    setPendingRoleChange({ userId: id, newRole, targetName: target?.name || target?.email || "회원", currentRole });
  };

  const handleConfirmRoleChange = async () => {
    if (!pendingRoleChange || !roleConfirmPassword) return;
    setRoleConfirmLoading(true);
    try {
      const { data, error } = await supabase.functions.invoke("update-user-role", {
        body: {
          userId: pendingRoleChange.userId,
          newRole: pendingRoleChange.newRole,
          currentPassword: roleConfirmPassword,
        },
      });

      if (error) throw error;
      if (data?.error) throw new Error(data.error);

      await fetchUsers();
      const resetNotice = data?.clearedFactorCount > 0 ? ` 관리자 MFA ${data.clearedFactorCount}개도 함께 초기화되었습니다.` : "";
      alert(`역할이 변경되었습니다.${resetNotice}`);
      setPendingRoleChange(null);
      setRoleConfirmPassword("");
      setShowRolePassword(false);
    } catch (err: unknown) {
      const message = await extractFunctionErrorMessage(err, "역할 변경 중 오류가 발생했습니다.");
      alert("역할 변경 실패: " + message);
      setRoleConfirmPassword("");
    } finally {
      setRoleConfirmLoading(false);
    }
  };

  const handleResetUserMfa = async (id: string) => {
    if (id === adminId) {
      alert("본인 계정의 MFA는 이 경로로 초기화할 수 없습니다.");
      return;
    }
    const target = users.find((u) => u.id === id);
    setPendingMfaReset({ userId: id, targetName: target?.name || target?.email || "회원" });
  };

  const handleConfirmMfaReset = async () => {
    if (!pendingMfaReset || !roleConfirmPassword) return;
    setRoleConfirmLoading(true);
    try {
      const { data, error } = await supabase.functions.invoke("reset-mfa", {
        body: {
          userId: pendingMfaReset.userId,
          currentPassword: roleConfirmPassword,
        },
      });

      if (error) throw error;
      if (data?.error) throw new Error(data.error);

      alert(`MFA가 초기화되었습니다.${data?.clearedFactorCount ? ` 삭제된 factor ${data.clearedFactorCount}개` : ""}`);
      setPendingMfaReset(null);
      setRoleConfirmPassword("");
      setShowRolePassword(false);
    } catch (err: unknown) {
      const message = await extractFunctionErrorMessage(err, "MFA 초기화 중 오류가 발생했습니다.");
      alert("MFA 초기화 실패: " + message);
      setRoleConfirmPassword("");
    } finally {
      setRoleConfirmLoading(false);
    }
  };

  // ── 가입 승인 / 반려 ───────────────────────────────────────
  const handleSetStatus = async (id: string, action: "approve" | "reject") => {
    if (id === adminId) { alert("본인 계정의 상태는 변경할 수 없습니다."); return; }
    const target = users.find(u => u.id === id);
    const name = target?.name || target?.email || "회원";
    const label = action === "approve" ? "승인" : "반려";
    if (!window.confirm(`'${name}' 회원의 가입을 ${label}하시겠습니까?`)) return;
    try {
      const { data, error } = await supabase.functions.invoke("update-user-status", {
        body: { userId: id, action },
      });
      if (error) throw error;
      if (data?.error) throw new Error(data.error);
      await fetchUsers();
      alert(`${label} 처리되었습니다.`);
    } catch (err: unknown) {
      const message = await extractFunctionErrorMessage(err, `${label} 처리 중 오류가 발생했습니다.`);
      alert(`${label} 실패: ` + message);
    }
  };

  // ── 회원 삭제 ──────────────────────────────────────────────
  const handleDeleteUser = async (id: string) => {
    if (!window.confirm("이 회원을 삭제하시겠습니까?\n삭제 후 해당 이메일로 재가입이 가능합니다.")) return;
    const { error } = await supabase.functions.invoke("delete-user", { body: { userId: id } });
    if (error) alert("삭제 실패: " + error.message);
  };

  // ── CSV 일괄 등록 ──────────────────────────────────────────
  const downloadCsvTemplate = () => {
    const csv = "﻿name,email,phone,company,role,password\n홍길동,hong@example.com,01012345678,스타트업A,user,\n김철수,kim@example.com,01098765432,스타트업B,participant,\n";
    const blob = new Blob([csv], { type: "text/csv;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a"); a.href = url; a.download = "회원_일괄등록_양식.csv"; a.click();
    URL.revokeObjectURL(url);
  };

  const handleCsvUpload = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    setCsvLoading(true);
    const reader = new FileReader();
    reader.onload = async (event) => {
      try {
        const text = event.target?.result as string;
        const rows = text.split(/\r?\n/).filter(row => row.trim() !== '');
        if (rows.length < 2) throw new Error("데이터가 없습니다.");

        const ALLOWED = new Set(["name", "email", "phone", "company", "role", "password"]);
        const parseLine = (line: string) => {
          const result: string[] = []; let cur = ""; let inQuote = false;
          for (const char of line) {
            if (char === '"') inQuote = !inQuote;
            else if (char === ',' && !inQuote) { result.push(cur.trim()); cur = ""; }
            else cur += char;
          }
          result.push(cur.trim());
          return result.map(v => v.replace(/^"|"$/g, ''));
        };

        const headers = parseLine(rows[0]);
        const invalid = headers.filter(h => h && !ALLOWED.has(h));
        if (invalid.length > 0) throw new Error(`허용되지 않은 컬럼: ${invalid.join(", ")}`);
        if (!headers.includes("email")) throw new Error("'email' 컬럼이 반드시 포함되어야 합니다.");
        if (!headers.includes("name"))  throw new Error("'name' 컬럼이 반드시 포함되어야 합니다.");

        const newUsers = rows.slice(1).map(row => {
          const values = parseLine(row);
          const obj: Record<string, string> = {};
          headers.forEach((h, i) => { if (h && ALLOWED.has(h)) obj[h] = values[i] || ""; });
          return obj;
        });

        if (!window.confirm(
          `${newUsers.length}명의 계정을 새로 생성하시겠습니까?\n` +
          `비밀번호가 비어있는 경우 임시 비밀번호(GXP-XXXX-XXXX)가 자동 생성됩니다.\n` +
          `admin 역할은 보안상 CSV 등록이 불가하며 일반 회원으로 등록됩니다.`
        )) return;

        const { data, error } = await supabase.functions.invoke("bulk-register-users", { body: { users: newUsers } });
        if (error) throw error;
        setBulkResult(data);
        await fetchUsers();
      } catch (err: unknown) {
        const message = typeof err === "object" && err !== null && "message" in err && typeof err.message === "string"
          ? err.message
          : "알 수 없는 오류";
        alert("CSV 처리 실패: " + message);
      } finally {
        setCsvLoading(false);
        e.target.value = "";
      }
    };
    reader.readAsText(file);
  };

  // ── 페이지네이션 ───────────────────────────────────────────
  const filtered = users.filter(u => {
    const q = search.toLowerCase();
    return (u.name || "").toLowerCase().includes(q) || (u.email || "").toLowerCase().includes(q) || (u.company || "").toLowerCase().includes(q);
  });
  const totalPages = Math.ceil(filtered.length / usersPerPage);
  const currentList = filtered.slice((currentPage - 1) * usersPerPage, currentPage * usersPerPage);
  const pendingCount = users.filter(u => u.status === "pending").length;

  return (
    <div style={{ display: "flex", flexDirection: "column", gap: "24px" }}>
      {/* 헤더 */}
      <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
        <div className="flex items-center gap-2.5">
          <h3 style={{ fontSize: "24px", fontWeight: 800, color: textMain, margin: 0 }}>회원 관리 ({loading ? "…" : users.length})</h3>
          {!loading && pendingCount > 0 && (
            <span style={{ fontSize: 13, fontWeight: 750, color: STATUS_CFG.pending.fg, background: STATUS_CFG.pending.bg, border: `1px solid ${STATUS_CFG.pending.border}`, padding: "5px 11px", borderRadius: 99, whiteSpace: "nowrap" }}>
              승인 대기 {pendingCount}
            </span>
          )}
        </div>
        <div className="flex flex-wrap items-center gap-2 sm:gap-[10px]" style={{ alignItems: "center" }}>
          <button onClick={downloadCsvTemplate} style={{ padding: "10px 16px", borderRadius: "10px", border: `1px solid ${border}`, background: panelBg, color: textMain, fontWeight: 700, cursor: "pointer", fontSize: "14px" }}>CSV 양식 다운로드</button>
          <label style={{ padding: "10px 16px", borderRadius: "10px", border: `1px solid ${csvLoading ? border : labelBorder}`, background: csvLoading ? panelBg : selectedBg, color: csvLoading ? textMuted : textMain, fontWeight: 750, cursor: csvLoading ? "not-allowed" : "pointer", display: "inline-block", fontSize: "14px" }}>
            {csvLoading ? "처리 중..." : "CSV 일괄 등록"}
            <input type="file" accept=".csv" onChange={handleCsvUpload} disabled={csvLoading} style={{ display: "none" }} />
          </label>
        </div>
      </div>

      {/* CSV 안내 */}
      <div style={{ fontSize: 13, color: textMuted, background: panelBg, border: `1px solid ${border}`, borderRadius: 12, padding: "12px 14px", lineHeight: 1.7 }}>
        <strong style={{ color: textMain }}>CSV 형식:</strong> name, email, phone, company, role, password<br />
        password가 비어있으면 <code style={{ fontFamily: `"SF Mono", monospace`, fontSize: 11 }}>GXP-XXXX-XXXX</code> 형식의 임시 비밀번호가 자동 생성됩니다. role은 <code style={{ fontFamily: `"SF Mono", monospace`, fontSize: 11 }}>user</code> 또는 <code style={{ fontFamily: `"SF Mono", monospace`, fontSize: 11 }}>participant</code>만 허용됩니다.
      </div>

      {/* 검색 */}
      <input
        type="text"
        placeholder="이름 / 이메일 / 회사 검색..."
        value={search}
        onChange={e => { setSearch(e.target.value); setCurrentPage(1); }}
        style={{ width: "100%", maxWidth: 420, padding: "12px 16px", borderRadius: 12, border: `1px solid ${border}`, background: inputBg, color: textMain, outline: "none", fontSize: 14 }}
      />

      {/* 회원 목록 */}
      <div style={{ display: "flex", flexDirection: "column", gap: 12 }}>
        {loading
          ? Array.from({ length: 6 }).map((_, i) => <Sk key={i} />)
          : currentList.length === 0
            ? <div style={{ padding: "40px", textAlign: "center", color: textMuted }}>회원이 없습니다.</div>
            : currentList.map(user => {
                const cfg = ROLE_CFG[user.role] ?? ROLE_CFG.user;
                const st = STATUS_CFG[user.status] ?? STATUS_CFG.approved;
                const isPending = user.status === "pending";
                const isSelf = user.id === adminId;
                return (
                  <div key={user.id} className="flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between" style={{ background: card, border: `1px solid ${isSelf ? labelBorder : border}`, borderRadius: "16px", padding: "18px 20px" }}>
                    <div style={{ display: "flex", alignItems: "center", gap: "10px", minWidth: 0 }}>
                      <span style={{ fontSize: "13px", background: labelBg, border: `1px solid ${labelBorder}`, color: textMuted, padding: "6px 10px", borderRadius: "9px", fontWeight: 700, whiteSpace: "nowrap" }}>{cfg.label}</span>
                      <span style={{ fontSize: "12px", background: st.bg, border: `1px solid ${st.border}`, color: st.fg, padding: "5px 9px", borderRadius: "99px", fontWeight: 750, whiteSpace: "nowrap" }}>{st.label}</span>
                      <div style={{ display: "flex", flexDirection: "column" }}>
                        <div style={{ display: "flex", alignItems: "center", gap: 8 }}>
                          <strong style={{ color: textMain, fontSize: "17px" }}>{user.name || "이름 없음"}</strong>
                          {isSelf && <span style={{ fontSize: 12, fontWeight: 750, color: textMain, background: selectedBg, border: `1px solid ${labelBorder}`, padding: "3px 8px", borderRadius: 99 }}>본인</span>}
                        </div>
                        <div style={{ display: "flex", alignItems: "center", gap: 8, marginTop: "4px", minWidth: 0 }}>
                          <span style={{ color: textMuted, fontSize: "14px", overflow: "hidden", textOverflow: "ellipsis", whiteSpace: "nowrap" }}>{user.email || "이메일 없음"}</span>
                          {user.company && (
                            <span style={{ color: textMuted, fontSize: "13px", background: labelBg, border: `1px solid ${labelBorder}`, padding: "2px 8px", borderRadius: "7px", fontWeight: 700, whiteSpace: "nowrap" }}>{user.company}</span>
                          )}
                        </div>
                      </div>
                    </div>
                    <div className="flex w-full flex-col gap-2 sm:w-auto sm:flex-row sm:items-center" style={{ alignItems: "stretch" }}>
                      {isPending && !isSelf && (
                        <>
                          <button
                            onClick={() => handleSetStatus(user.id, "approve")}
                            style={{ padding: "10px 18px", borderRadius: "10px", border: `1px solid ${STATUS_CFG.approved.border}`, background: STATUS_CFG.approved.bg, color: STATUS_CFG.approved.fg, fontWeight: 750, cursor: "pointer", fontSize: 14 }}
                          >승인</button>
                          <button
                            onClick={() => handleSetStatus(user.id, "reject")}
                            style={{ padding: "10px 18px", borderRadius: "10px", border: `1px solid ${deleteBorder}`, background: deleteBg, color: "var(--color-brand-red)", fontWeight: 750, cursor: "pointer", fontSize: 14 }}
                          >반려</button>
                        </>
                      )}
                      <select
                        value={user.role ?? "user"}
                        onChange={e => handleSetRole(user.id, e.target.value)}
                        disabled={isSelf}
                        style={{ padding: "10px 12px", borderRadius: "10px", border: `1px solid ${border}`, background: inputBg, color: isSelf ? textMuted : textMain, fontWeight: 700, cursor: isSelf ? "not-allowed" : "pointer", fontSize: 14, opacity: isSelf ? 0.45 : 1 }}
                      >
                        <option value="admin">관리자</option>
                        <option value="participant">참여사 담당자</option>
                        <option value="user">일반 회원</option>
                      </select>
                      <button
                        onClick={() => handleDeleteUser(user.id)}
                        disabled={isSelf}
                        style={{ padding: "10px 18px", borderRadius: "10px", border: `1px solid ${isSelf ? border : deleteBorder}`, background: isSelf ? panelBg : deleteBg, color: isSelf ? textMuted : "var(--color-brand-red)", fontWeight: 700, cursor: isSelf ? "not-allowed" : "pointer", opacity: isSelf ? 0.45 : 1, fontSize: 14 }}
                      >삭제</button>
                      {user.role === "admin" && (
                        <button
                          onClick={() => handleResetUserMfa(user.id)}
                          disabled={isSelf}
                          style={{ padding: "10px 18px", borderRadius: "10px", border: `1px solid ${isSelf ? border : deleteBorder}`, background: isSelf ? panelBg : deleteBg, color: isSelf ? textMuted : "var(--color-brand-red)", fontWeight: 700, cursor: isSelf ? "not-allowed" : "pointer", opacity: isSelf ? 0.45 : 1, fontSize: 14 }}
                        >
                          MFA 초기화
                        </button>
                      )}
                    </div>
                  </div>
                );
              })}
      </div>

      {/* 페이지네이션 */}
      {totalPages > 1 && (
        <div style={{ display: "flex", justifyContent: "center", gap: 8 }}>
          <button onClick={() => setCurrentPage(p => Math.max(1, p - 1))} disabled={currentPage === 1} style={{ padding: "8px 14px", borderRadius: 8, border: `1px solid ${border}`, background: card, color: textMain, cursor: currentPage === 1 ? "not-allowed" : "pointer", fontWeight: 600 }}>이전</button>
          {[...Array(totalPages)].map((_, i) => (
            <button key={i} onClick={() => setCurrentPage(i + 1)} style={{ padding: "8px 16px", borderRadius: 8, cursor: "pointer", border: `1px solid ${currentPage === i + 1 ? labelBorder : border}`, background: currentPage === i + 1 ? selectedBg : card, color: textMain, fontWeight: currentPage === i + 1 ? 800 : 500 }}>{i + 1}</button>
          ))}
          <button onClick={() => setCurrentPage(p => Math.min(totalPages, p + 1))} disabled={currentPage === totalPages} style={{ padding: "8px 14px", borderRadius: 8, border: `1px solid ${border}`, background: card, color: textMain, cursor: currentPage === totalPages ? "not-allowed" : "pointer", fontWeight: 600 }}>다음</button>
        </div>
      )}

      {pendingRoleChange && (
        <AdminRoleModal
          pendingRoleChange={pendingRoleChange}
          roleConfirmPassword={roleConfirmPassword}
          setRoleConfirmPassword={setRoleConfirmPassword}
          showRolePassword={showRolePassword}
          setShowRolePassword={setShowRolePassword}
          roleConfirmLoading={roleConfirmLoading}
          roleLabels={ROLE_LABELS}
          onConfirm={handleConfirmRoleChange}
          onCancel={() => { setPendingRoleChange(null); setRoleConfirmPassword(""); setShowRolePassword(false); }}
        />
      )}

      {pendingMfaReset && (
        <AdminMfaResetModal
          pendingMfaReset={pendingMfaReset}
          roleConfirmPassword={roleConfirmPassword}
          setRoleConfirmPassword={setRoleConfirmPassword}
          showRolePassword={showRolePassword}
          setShowRolePassword={setShowRolePassword}
          roleConfirmLoading={roleConfirmLoading}
          onConfirm={handleConfirmMfaReset}
          onCancel={() => { setPendingMfaReset(null); setRoleConfirmPassword(""); setShowRolePassword(false); }}
        />
      )}

      {bulkResult && (
        <AdminBulkResultModal
          results={bulkResult.results}
          onClose={() => setBulkResult(null)}
        />
      )}
    </div>
  );
}

export default AdminUserManagement;
