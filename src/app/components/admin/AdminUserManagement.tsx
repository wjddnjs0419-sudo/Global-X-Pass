import { useState, useEffect, useCallback } from "react";
import { createClient } from "@supabase/supabase-js";
import { useTheme } from "../../ThemeContext";
import { supabase, supabaseUrl, supabaseAnonKey } from "../../../lib/supabaseClient";
import { AdminRoleModal } from "./AdminRoleModal";
import { AdminBulkResultModal } from "./AdminBulkResultModal";

interface AdminUserManagementProps {
  refreshKey: number;
  adminId: string;
  adminEmail: string;
}

const ROLE_CFG: Record<string, { label: string; color: string; bg: string }> = {
  admin:       { label: "관리자",        color: "#4377F1", bg: "rgba(67,119,241,0.1)"  },
  participant: { label: "참여사 담당자", color: "#18A343", bg: "rgba(24,163,67,0.1)"   },
  user:        { label: "일반 회원",     color: "#6B7280", bg: "rgba(107,114,128,0.1)" },
};
const ROLE_LABELS: Record<string, string> = { admin: "관리자", participant: "참여사 담당자", user: "일반 회원" };

type RegisterResult = { email: string; name: string; success: boolean; tempPassword?: string; wasAutoGenerated?: boolean; error?: string };

export function AdminUserManagement({ refreshKey, adminId, adminEmail }: AdminUserManagementProps) {
  const { isDark } = useTheme();

  const [users, setUsers]               = useState<any[]>([]);
  const [loading, setLoading]           = useState(true);
  const [search, setSearch]             = useState("");
  const [currentPage, setCurrentPage]   = useState(1);
  const [csvLoading, setCsvLoading]     = useState(false);
  const [bulkResult, setBulkResult]     = useState<{ results: RegisterResult[] } | null>(null);

  const [pendingRoleChange, setPendingRoleChange] = useState<{ userId: string; newRole: string; targetName: string; currentRole: string } | null>(null);
  const [roleConfirmPassword, setRoleConfirmPassword] = useState("");
  const [roleConfirmLoading, setRoleConfirmLoading]   = useState(false);
  const [showRolePassword, setShowRolePassword]       = useState(false);

  const usersPerPage = 10;

  const card     = isDark ? "rgba(255,255,255,0.04)" : "#ffffff";
  const border   = isDark ? "rgba(255,255,255,0.08)" : "rgba(0,0,0,0.08)";
  const textMain = isDark ? "rgba(255,255,255,0.92)" : "rgba(10,16,32,0.88)";
  const textMuted= isDark ? "rgba(255,255,255,0.45)" : "rgba(10,16,32,0.45)";
  const inputBg  = isDark ? "rgba(255,255,255,0.04)" : "#fff";
  const skBg     = isDark ? "rgba(255,255,255,0.07)" : "rgba(0,0,0,0.06)";

  const Sk = ({ h = 78 }: { h?: number }) => (
    <div style={{ height: h, borderRadius: 20, background: skBg, animation: "pulse 1.5s ease-in-out infinite" }} />
  );

  const fetchUsers = useCallback(async () => {
    setLoading(true);
    const { data, error } = await supabase.functions.invoke('decrypt-profiles');
    if (error) console.error("회원 데이터 불러오기 오류:", error.message);
    if (data) setUsers(data);
    setLoading(false);
  }, []);

  useEffect(() => { fetchUsers(); }, [refreshKey]);

  // ── 역할 변경 ──────────────────────────────────────────────
  const handleSetRole = async (id: string, newRole: string) => {
    if (id === adminId) { alert("본인 계정의 권한은 변경할 수 없습니다."); return; }
    const target = users.find(u => u.id === id);
    const currentRole = target?.role ?? "user";
    const isAdminChange = newRole === "admin" || currentRole === "admin";
    if (isAdminChange) {
      setPendingRoleChange({ userId: id, newRole, targetName: target?.name || target?.email || "회원", currentRole });
      return;
    }
    if (!window.confirm(`역할을 '${ROLE_LABELS[newRole]}'로 변경하시겠습니까?`)) return;
    const { error } = await supabase.from('profiles').update({ role: newRole }).eq('id', id);
    if (error) { alert("역할 변경 실패: " + error.message); return; }
    await fetchUsers();
  };

  const handleConfirmRoleChange = async () => {
    if (!pendingRoleChange || !roleConfirmPassword) return;
    setRoleConfirmLoading(true);

    const noopStorage = {
      getItem: (_k: string): string | null => null,
      setItem: (_k: string, _v: string): void => {},
      removeItem: (_k: string): void => {},
    };
    const tempClient = createClient(supabaseUrl, supabaseAnonKey, {
      auth: { storage: noopStorage, persistSession: false, autoRefreshToken: false },
    });
    const { error: authError } = await tempClient.auth.signInWithPassword({ email: adminEmail, password: roleConfirmPassword });
    if (authError) {
      alert("비밀번호가 올바르지 않습니다. 다시 확인해주세요.");
      setRoleConfirmPassword("");
      setRoleConfirmLoading(false);
      return;
    }

    const { error } = await supabase.from('profiles').update({ role: pendingRoleChange.newRole }).eq('id', pendingRoleChange.userId);
    if (error) { alert("역할 변경 실패: " + error.message); }
    else { await fetchUsers(); alert("역할이 변경되었습니다."); }

    setPendingRoleChange(null);
    setRoleConfirmPassword("");
    setShowRolePassword(false);
    setRoleConfirmLoading(false);
  };

  // ── 회원 삭제 ──────────────────────────────────────────────
  const handleDeleteUser = async (id: string) => {
    if (!window.confirm("이 회원을 삭제하시겠습니까?\n삭제 후 해당 이메일로 재가입이 가능합니다.")) return;
    const { error } = await supabase.functions.invoke("delete-user", { body: { userId: id } });
    if (error) alert("삭제 실패: " + error.message);
  };

  // ── CSV 일괄 등록 ──────────────────────────────────────────
  const downloadCsvTemplate = () => {
    const csv = "﻿name,email,phone,company,role,password\n홍길동,hong@example.com,01012345678,스타트업A,user,\n김철수,kim@example.com,01098765432,스타트업B,participant,\n";
    const blob = new Blob([csv], { type: "text/csv;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a"); a.href = url; a.download = "회원_일괄등록_양식.csv"; a.click();
    URL.revokeObjectURL(url);
  };

  const handleCsvUpload = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    setCsvLoading(true);
    const reader = new FileReader();
    reader.onload = async (event) => {
      try {
        const text = event.target?.result as string;
        const rows = text.split(/\r?\n/).filter(row => row.trim() !== '');
        if (rows.length < 2) throw new Error("데이터가 없습니다.");

        const ALLOWED = new Set(["name", "email", "phone", "company", "role", "password"]);
        const parseLine = (line: string) => {
          const result: string[] = []; let cur = ""; let inQuote = false;
          for (const char of line) {
            if (char === '"') inQuote = !inQuote;
            else if (char === ',' && !inQuote) { result.push(cur.trim()); cur = ""; }
            else cur += char;
          }
          result.push(cur.trim());
          return result.map(v => v.replace(/^"|"$/g, ''));
        };

        const headers = parseLine(rows[0]);
        const invalid = headers.filter(h => h && !ALLOWED.has(h));
        if (invalid.length > 0) throw new Error(`허용되지 않은 컬럼: ${invalid.join(", ")}`);
        if (!headers.includes("email")) throw new Error("'email' 컬럼이 반드시 포함되어야 합니다.");
        if (!headers.includes("name"))  throw new Error("'name' 컬럼이 반드시 포함되어야 합니다.");

        const newUsers = rows.slice(1).map(row => {
          const values = parseLine(row);
          const obj: Record<string, string> = {};
          headers.forEach((h, i) => { if (h && ALLOWED.has(h)) obj[h] = values[i] || ""; });
          return obj;
        });

        if (!window.confirm(
          `${newUsers.length}명의 계정을 새로 생성하시겠습니까?\n` +
          `비밀번호가 비어있는 경우 임시 비밀번호(GXP-XXXX-XXXX)가 자동 생성됩니다.\n` +
          `admin 역할은 보안상 CSV 등록이 불가하며 일반 회원으로 등록됩니다.`
        )) return;

        const { data, error } = await supabase.functions.invoke("bulk-register-users", { body: { users: newUsers } });
        if (error) throw error;
        setBulkResult(data);
        await fetchUsers();
      } catch (err: any) {
        alert("CSV 처리 실패: " + err.message);
      } finally {
        setCsvLoading(false);
        e.target.value = "";
      }
    };
    reader.readAsText(file);
  };

  // ── 페이지네이션 ───────────────────────────────────────────
  const filtered = users.filter(u => {
    const q = search.toLowerCase();
    return (u.name || "").toLowerCase().includes(q) || (u.email || "").toLowerCase().includes(q) || (u.company || "").toLowerCase().includes(q);
  });
  const totalPages = Math.ceil(filtered.length / usersPerPage);
  const currentList = filtered.slice((currentPage - 1) * usersPerPage, currentPage * usersPerPage);

  return (
    <div style={{ display: "flex", flexDirection: "column", gap: "24px" }}>
      {/* 헤더 */}
      <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center" }}>
        <h3 style={{ fontSize: "22px", fontWeight: 800, color: textMain }}>회원 관리 ({loading ? "…" : users.length})</h3>
        <div style={{ display: "flex", gap: 10, alignItems: "center" }}>
          <button onClick={downloadCsvTemplate} style={{ padding: "10px 16px", borderRadius: "10px", border: `1px solid ${border}`, background: isDark ? "rgba(255,255,255,0.06)" : "#f8fafc", color: textMain, fontWeight: 700, cursor: "pointer", fontSize: "14px" }}>CSV 양식 다운로드</button>
          <label style={{ padding: "10px 16px", borderRadius: "10px", background: csvLoading ? (isDark ? "rgba(255,255,255,0.1)" : "#e2e8f0") : "#4377F1", color: csvLoading ? textMuted : "#fff", fontWeight: 700, cursor: csvLoading ? "not-allowed" : "pointer", display: "inline-block", fontSize: "14px" }}>
            {csvLoading ? "처리 중..." : "CSV 일괄 등록"}
            <input type="file" accept=".csv" onChange={handleCsvUpload} disabled={csvLoading} style={{ display: "none" }} />
          </label>
        </div>
      </div>

      {/* CSV 안내 */}
      <div style={{ fontSize: 12, color: textMuted, background: isDark ? "rgba(255,255,255,0.03)" : "#f8fafc", border: `1px solid ${border}`, borderRadius: 10, padding: "10px 14px", lineHeight: 1.7 }}>
        <strong style={{ color: textMain }}>CSV 형식:</strong> name, email, phone, company, role, password<br />
        password가 비어있으면 <code style={{ fontFamily: `"SF Mono", monospace`, fontSize: 11 }}>GXP-XXXX-XXXX</code> 형식의 임시 비밀번호가 자동 생성됩니다. role은 <code style={{ fontFamily: `"SF Mono", monospace`, fontSize: 11 }}>user</code> 또는 <code style={{ fontFamily: `"SF Mono", monospace`, fontSize: 11 }}>participant</code>만 허용됩니다.
      </div>

      {/* 검색 */}
      <input
        type="text"
        placeholder="이름 / 이메일 / 회사 검색..."
        value={search}
        onChange={e => { setSearch(e.target.value); setCurrentPage(1); }}
        style={{ padding: "12px 16px", borderRadius: 12, border: `1px solid ${border}`, background: inputBg, color: textMain, outline: "none", fontSize: 14 }}
      />

      {/* 회원 목록 */}
      <div style={{ display: "flex", flexDirection: "column", gap: 12 }}>
        {loading
          ? Array.from({ length: 5 }).map((_, i) => <Sk key={i} />)
          : currentList.length === 0
            ? <div style={{ padding: "40px", textAlign: "center", color: textMuted }}>회원이 없습니다.</div>
            : currentList.map(user => {
                const cfg = ROLE_CFG[user.role] ?? ROLE_CFG.user;
                const isSelf = user.id === adminId;
                return (
                  <div key={user.id} className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-[16px] sm:gap-0" style={{ background: card, border: `1px solid ${isSelf ? "rgba(67,119,241,0.35)" : border}`, borderRadius: "20px", padding: "20px 30px" }}>
                    <div style={{ display: "flex", alignItems: "center", gap: "20px" }}>
                      <span style={{ fontSize: "12px", background: isDark ? cfg.color + "33" : cfg.bg, color: cfg.color, padding: "6px 12px", borderRadius: "8px", fontWeight: 700, whiteSpace: "nowrap" }}>{cfg.label}</span>
                      <div style={{ display: "flex", flexDirection: "column" }}>
                        <div style={{ display: "flex", alignItems: "center", gap: 8 }}>
                          <strong style={{ color: textMain, fontSize: "16px" }}>{user.name || "이름 없음"}</strong>
                          {isSelf && <span style={{ fontSize: 11, fontWeight: 700, color: "#4377F1", background: "rgba(67,119,241,0.12)", padding: "2px 8px", borderRadius: 99 }}>본인</span>}
                        </div>
                        <span style={{ color: textMuted, fontSize: "13px", marginTop: "4px" }}>{user.email || "이메일 없음"}</span>
                      </div>
                    </div>
                    <div style={{ display: "flex", gap: 10, alignItems: "center" }}>
                      <select
                        value={user.role ?? "user"}
                        onChange={e => handleSetRole(user.id, e.target.value)}
                        disabled={isSelf}
                        style={{ padding: "9px 12px", borderRadius: "10px", border: `1px solid ${border}`, background: inputBg, color: isSelf ? textMuted : textMain, fontWeight: 700, cursor: isSelf ? "not-allowed" : "pointer", fontSize: 13, opacity: isSelf ? 0.45 : 1 }}
                      >
                        <option value="admin">관리자</option>
                        <option value="participant">참여사 담당자</option>
                        <option value="user">일반 회원</option>
                      </select>
                      <button
                        onClick={() => handleDeleteUser(user.id)}
                        disabled={isSelf}
                        style={{ padding: "10px 18px", borderRadius: "10px", border: "none", background: isSelf ? (isDark ? "rgba(255,255,255,0.06)" : "#f1f5f9") : "#fee2e2", color: isSelf ? textMuted : "#ef4444", fontWeight: 700, cursor: isSelf ? "not-allowed" : "pointer", opacity: isSelf ? 0.45 : 1 }}
                      >삭제</button>
                    </div>
                  </div>
                );
              })}
      </div>

      {/* 페이지네이션 */}
      {totalPages > 1 && (
        <div style={{ display: "flex", justifyContent: "center", gap: 8 }}>
          <button onClick={() => setCurrentPage(p => Math.max(1, p - 1))} disabled={currentPage === 1} style={{ padding: "8px 14px", borderRadius: 8, border: `1px solid ${border}`, background: card, color: textMain, cursor: currentPage === 1 ? "not-allowed" : "pointer", fontWeight: 600 }}>이전</button>
          {[...Array(totalPages)].map((_, i) => (
            <button key={i} onClick={() => setCurrentPage(i + 1)} style={{ padding: "8px 16px", borderRadius: 8, cursor: "pointer", border: currentPage === i + 1 ? `1px solid #4377F1` : `1px solid ${border}`, background: currentPage === i + 1 ? "#4377F1" : card, color: currentPage === i + 1 ? "#fff" : textMain, fontWeight: currentPage === i + 1 ? 800 : 500 }}>{i + 1}</button>
          ))}
          <button onClick={() => setCurrentPage(p => Math.min(totalPages, p + 1))} disabled={currentPage === totalPages} style={{ padding: "8px 14px", borderRadius: 8, border: `1px solid ${border}`, background: card, color: textMain, cursor: currentPage === totalPages ? "not-allowed" : "pointer", fontWeight: 600 }}>다음</button>
        </div>
      )}

      {pendingRoleChange && (
        <AdminRoleModal
          pendingRoleChange={pendingRoleChange}
          roleConfirmPassword={roleConfirmPassword}
          setRoleConfirmPassword={setRoleConfirmPassword}
          showRolePassword={showRolePassword}
          setShowRolePassword={setShowRolePassword}
          roleConfirmLoading={roleConfirmLoading}
          roleLabels={ROLE_LABELS}
          onConfirm={handleConfirmRoleChange}
          onCancel={() => { setPendingRoleChange(null); setRoleConfirmPassword(""); setShowRolePassword(false); }}
        />
      )}

      {bulkResult && (
        <AdminBulkResultModal
          results={bulkResult.results}
          onClose={() => setBulkResult(null)}
        />
      )}
    </div>
  );
}

export default AdminUserManagement;
