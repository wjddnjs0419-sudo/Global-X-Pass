import { createClient } from "https://esm.sh/@supabase/supabase-js@2";
import { corsHeaders } from "../_shared/cors.ts";

const ENC_PREFIX = "enc:v1:";

async function deriveKey(secret: string): Promise<CryptoKey> {
  const rawKey = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(secret));
  return crypto.subtle.importKey("raw", rawKey, { name: "AES-GCM" }, false, ["encrypt"]);
}

function bytesToHex(bytes: Uint8Array): string {
  return Array.from(bytes).map((b) => b.toString(16).padStart(2, "0")).join("");
}

async function encrypt(plaintext: string | null, key: CryptoKey): Promise<string | null> {
  if (!plaintext || plaintext.startsWith(ENC_PREFIX)) return plaintext;
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const encoded = new TextEncoder().encode(plaintext);
  const encrypted = new Uint8Array(
    await crypto.subtle.encrypt({ name: "AES-GCM", iv, tagLength: 128 }, key, encoded)
  );
  const ciphertext = encrypted.slice(0, encrypted.length - 16);
  const authTag = encrypted.slice(encrypted.length - 16);
  return `${ENC_PREFIX}${bytesToHex(iv)}:${bytesToHex(ciphertext)}:${bytesToHex(authTag)}`;
}

function generateTempPassword(): string {
  // GXP-XXXX-XXXX 형식 (모호한 문자 제외: 0, O, I, l, 1)
  const pool = "ABCDEFGHJKMNPQRSTUVWXYZ23456789";
  let suffix = "";
  for (let i = 0; i < 8; i++) {
    if (i === 4) suffix += "-";
    suffix += pool[Math.floor(Math.random() * pool.length)];
  }
  return `GXP-${suffix}`;
}

Deno.serve(async (req: Request) => {
  const CORS = corsHeaders(req);
  if (req.method === "OPTIONS") return new Response(null, { headers: CORS });

  try {
    const authHeader = req.headers.get("Authorization");
    if (!authHeader) return new Response("Unauthorized", { status: 401, headers: CORS });

    const supabaseUrl = Deno.env.get("SUPABASE_URL")!;
    const anonKey = Deno.env.get("SUPABASE_ANON_KEY")!;
    const serviceKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
    const encSecret = Deno.env.get("ENCRYPTION_SECRET_KEY");
    if (!encSecret) throw new Error("ENCRYPTION_SECRET_KEY is not configured");

    // 호출자가 어드민인지 확인
    const callerClient = createClient(supabaseUrl, anonKey, {
      global: { headers: { Authorization: authHeader } },
    });
    const { data: { user }, error: userErr } = await callerClient.auth.getUser();
    if (userErr || !user) return new Response("Unauthorized", { status: 401, headers: CORS });

    const adminClient = createClient(supabaseUrl, serviceKey);
    const { data: callerProfile } = await adminClient
      .from("profiles").select("role").eq("id", user.id).single();
    if (callerProfile?.role !== "admin") {
      return new Response("Forbidden", { status: 403, headers: CORS });
    }

    const { users } = await req.json();
    if (!Array.isArray(users) || users.length === 0) {
      return new Response(JSON.stringify({ error: "users 배열이 필요합니다." }), {
        status: 400, headers: { ...CORS, "Content-Type": "application/json" },
      });
    }

    const key = await deriveKey(encSecret);
    const results: object[] = [];

    for (const u of users) {
      const email = (u.email ?? "").trim();
      const name = (u.name ?? "").trim();
      if (!email || !name) {
        results.push({ email, name, success: false, error: "이메일 또는 이름이 비어있습니다." });
        continue;
      }

      const providedPassword = (u.password ?? "").trim();
      if (providedPassword && providedPassword.length < 8) {
        results.push({ email, name, success: false, error: "비밀번호는 최소 8자 이상이어야 합니다." });
        continue;
      }

      const tempPassword = providedPassword || generateTempPassword();
      const wasAutoGenerated = !providedPassword;

      // admin 역할은 CSV 일괄 등록으로 부여 불가
      const ALLOWED_ROLES = new Set(["participant", "user"]);
      const role = ALLOWED_ROLES.has(u.role) ? u.role : "user";

      try {
        const { data: created, error: createError } = await adminClient.auth.admin.createUser({
          email,
          password: tempPassword,
          email_confirm: true,
          user_metadata: { name },
        });

        if (createError) {
          results.push({ email, name, success: false, error: createError.message });
          continue;
        }

        const userId = created.user.id;

        // handle_new_user 트리거가 profiles 행 생성 후 추가 필드 업데이트
        await adminClient.from("profiles").update({
          name,
          phone: (u.phone ?? "").trim() || null,
          company: (u.company ?? "").trim() || null,
          role,
        }).eq("id", userId);

        // 최신 profiles 행(email 포함) 조회 후 PII 인라인 암호화
        const { data: profile } = await adminClient
          .from("profiles").select("name, email, phone").eq("id", userId).single();

        if (profile) {
          await adminClient.from("profiles").update({
            name: await encrypt(profile.name, key),
            email: await encrypt(profile.email, key),
            phone: await encrypt(profile.phone, key),
          }).eq("id", userId);
        }

        results.push({ email, name, success: true, tempPassword, wasAutoGenerated });
      } catch (err) {
        results.push({ email, name, success: false, error: String(err) });
      }
    }

    return new Response(JSON.stringify({ results }), {
      headers: { ...CORS, "Content-Type": "application/json" },
    });
  } catch (err) {
    console.error("[bulk-register-users]", err);
    return new Response(JSON.stringify({ error: (err as Error).message }), {
      status: 500, headers: { ...CORS, "Content-Type": "application/json" },
    });
  }
});
